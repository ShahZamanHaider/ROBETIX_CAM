"""Extract a small public PEM CA store from the pinned Mozilla export.
The Arduino 2.x bundle callback cannot reliably anchor cross-signed chains.
Native mbedTLS PEM verification retains hostname, signature and time checks.
"""
from pathlib import Path
import re,ssl,hashlib,sys
root=Path(__file__).resolve().parents[1]
source=(root/'certs/mozilla.pem').read_text(encoding='utf-8')
expected=(root/'certs/mozilla.sha256').read_text().split()[0]
if hashlib.sha256((root/'certs/mozilla.pem').read_bytes()).hexdigest()!=expected:
 raise RuntimeError('Pinned Mozilla export checksum mismatch')
names=['ISRG Root X1','ISRG Root X2','GTS Root R1','GTS Root R3','GTS Root R4']
blocks=[]
for name in names:
 match=re.search(r'^'+re.escape(name)+r'\n=+\n# Fingerprint \(SHA-256\): ([A-F0-9:]+)\n(-----BEGIN CERTIFICATE-----\n.*?-----END CERTIFICATE-----)',source,re.M|re.S)
 if not match:raise RuntimeError('Missing public root '+name)
 pem=match[2]+'\n';digest=hashlib.sha256(ssl.PEM_cert_to_DER_cert(pem)).hexdigest()
 if digest!=match[1].replace(':','').lower():raise RuntimeError('Root fingerprint mismatch')
 blocks.append(pem)
pem=''.join(blocks)
outputs={'certs/service-roots.pem':pem,'src/TlsRoots.h':'#pragma once\n// Public Mozilla CA anchors; generated by tools/build-service-roots.py.\nstatic const char ROBETIX_SERVICE_ROOTS[] PROGMEM=R"CA('+pem+')CA";\n'}
for name,content in outputs.items():
 path=root/name
 if '--check'in sys.argv:
  if not path.exists() or path.read_text(encoding='utf-8')!=content:raise RuntimeError('Regenerate '+name)
 else:path.write_text(content,encoding='utf-8')
context=ssl.create_default_context(cadata=pem)
assert context.check_hostname and context.verify_mode==ssl.CERT_REQUIRED
print('PASS: five fingerprint-checked Mozilla PEM roots; native certificate/hostname validation enabled.')
